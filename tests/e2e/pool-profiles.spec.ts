import { expect, test } from '@playwright/test';
import type { FastifyInstance } from 'fastify';
import { resolve } from 'node:path';
import { createApp } from '../../src/server/app.js';
import { testDatabase } from '../helpers.js';

let fixture: Awaited<ReturnType<typeof testDatabase>>;
let app: FastifyInstance;
let url: string;
test.beforeAll(async () => {
  fixture = await testDatabase();
  app = await createApp(fixture.db, { webRoot: resolve('dist/web') });
  url = await app.listen({ port: 0, host: '127.0.0.1' });
});
test.afterAll(async () => { await app?.close(); await fixture?.close(); });

test('pool profile library, copying, persistence, explicit application, editing and deletion', async ({ page }) => {
  await page.goto(url);
  await page.getByLabel('Language').selectOption('en');
  await page.getByRole('button', { name: 'Try demo' }).first().click();
  await expect(page.getByRole('button', { name: 'Bitaxe 1', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Pool profiles', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Pool profiles', exact: true })).toBeVisible();
  await page.getByLabel('Copy from a Bitaxe').selectOption({ label: 'Bitaxe 1 · demo-1' });
  await page.getByLabel('Pool profile name').fill('Home pool');
  await page.getByLabel('Pool port', { exact: true }).fill('4444');
  await page.getByRole('button', { name: 'Save pool profile' }).click();
  await expect(page.getByRole('status')).toContainText('Pool profile saved');
  await page.reload();
  await page.getByRole('button', { name: /Home pool/ }).click();
  await expect(page.getByLabel('Pool port', { exact: true })).toHaveValue('4444');
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'test-results/pool-profiles-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/pool-profiles-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.getByRole('link', { name: 'View fleet' }).click();
  await page.getByRole('button', { name: 'Bitaxe 2', exact: true }).click();
  await page.getByLabel('Load pool profile').selectOption({ label: 'Home pool' });
  await expect(page.getByLabel('Pool port', { exact: true })).toHaveValue('4444');
  await page.getByLabel('Payout address / account.worker', { exact: true }).fill('demo.worker2');
  await page.getByRole('button', { name: 'Apply & verify' }).click();
  await expect(page.getByText('Verified', { exact: true }).first()).toBeVisible();
  await expect(page.getByLabel('Pool port', { exact: true })).toHaveAttribute('placeholder', '4444');
  await page.getByRole('link', { name: 'Pool profiles', exact: true }).click();
  await page.getByRole('button', { name: /Home pool/ }).click();
  await page.getByLabel('Pool profile name').fill('Updated pool');
  await page.getByRole('button', { name: 'Save pool profile' }).click();
  await expect(page.getByRole('button', { name: /Updated pool/ })).toBeVisible();
  await page.getByRole('button', { name: 'Delete profile' }).click();
  await page.getByRole('button', { name: 'Confirm deletion' }).click();
  await expect(page.getByRole('status')).toContainText('Pool profile deleted');
  await expect(page.getByRole('button', { name: /Updated pool/ })).toHaveCount(0);
  await page.getByLabel('Language').selectOption('pt-BR');
  await expect(page.getByRole('heading', { name: 'Perfis de pool', exact: true })).toBeVisible();
});


test('copy fallback as a portable profile and apply it without modifying primary on desktop and mobile', async ({ page }) => {
  await page.goto(url);
  await page.getByRole('button', { name: 'Try demo' }).first().click();
  await page.getByRole('link', { name: 'Pool profiles', exact: true }).click();
  await page.getByLabel('Pool to copy').selectOption('fallback');
  await page.getByLabel('Copy from a Bitaxe').selectOption({ label: 'Bitaxe 1 · demo-1' });
  await expect(page.getByLabel('Pool hostname', { exact: true })).toHaveValue('backup.example.com');
  await expect(page.getByLabel('Pool port', { exact: true })).toHaveValue('3334');
  await page.getByLabel('Pool profile name').fill('Fallback profile');
  await page.getByRole('button', { name: 'Save pool profile' }).click();
  await expect(page.getByRole('status')).toContainText('Pool profile saved');
  await page.getByRole('link', { name: 'View fleet' }).click();
  await page.getByRole('button', { name: 'Bitaxe 2', exact: true }).click();
  const primary = await page.getByLabel('Pool hostname', { exact: true }).getAttribute('placeholder');
  await page.getByLabel('Load fallback pool profile').selectOption({ label: 'Fallback profile' });
  await expect(page.getByLabel('Pool hostname', { exact: true })).toHaveValue('');
  await expect(page.getByLabel('Fallback pool hostname')).toHaveValue('backup.example.com');
  await page.getByLabel('Fallback pool port').fill('5555');
  await page.getByLabel('Fallback payout address / account.worker').fill('backup.worker2');
  await page.getByRole('button', { name: 'Apply & verify' }).click();
  await expect(page.getByText('Verified', { exact: true }).first()).toBeVisible();
  await expect(page.getByLabel('Fallback pool port')).toHaveAttribute('placeholder', '5555');
  await expect(page.getByLabel('Pool hostname', { exact: true })).toHaveAttribute('placeholder', primary!);
  await page.reload();
  await page.getByRole('button', { name: 'Bitaxe 2', exact: true }).click();
  await expect(page.getByLabel('Fallback pool port')).toHaveAttribute('placeholder', '5555');
  const fallback = page.getByRole('group', { name: 'Fallback pool', exact: true });
  await fallback.screenshot({ path: 'test-results/fallback-pool-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await fallback.screenshot({ path: 'test-results/fallback-pool-mobile.png' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByLabel('Language').selectOption('pt-BR');
  await expect(page.getByLabel('Carregar perfil no fallback')).toBeVisible();
});
