test('prefilled settings, visible unsaved edits, selective save and explicit miner restart', async ({ page }) => {
  await page.goto(url);
  await page.getByRole('button', { name: 'Try demo' }).first().click();
  await page.getByRole('button', { name: 'Bitaxe 3', exact: true }).click();
  await page.locator('.miner-disclosure > summary').first().click();
  await page.locator('.miner-disclosure > summary').nth(1).click();
  const config = page.locator('.configuration');
  const user = config.getByLabel('Payout address / account.worker', { exact: true });
  await expect(user).toHaveValue('demo.worker3');
  await expect(config.getByLabel('Pool port', { exact: true })).toHaveValue('3333');
  await expect(config.getByRole('combobox', { name: 'Frequency (MHz)', exact: true })).toHaveValue('525');
  await expect(config.getByLabel('Pool password', { exact: true })).toHaveValue('');
  await expect(config.getByRole('button', { name: 'Apply & verify' })).toBeDisabled();
  await user.fill('demo.changed3');
  await expect(user).toHaveClass(/is-dirty/);
  await expect(config.getByText('1 unsaved field', { exact: true })).toBeVisible();
  await expect(config.getByRole('button', { name: 'Restart miner' })).toBeDisabled();
  await config.screenshot({ path: 'test-results/configuration-unsaved-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await config.screenshot({ path: 'test-results/configuration-unsaved-mobile.png' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1280, height: 800 });
  const command = page.waitForRequest(request => request.url().endsWith('/api/batch') && request.method() === 'POST');
  await config.getByRole('button', { name: 'Apply & verify' }).click();
  expect((await command).postDataJSON().settings).toEqual({ stratumUser: 'demo.changed3' });
  await expect(user).toHaveValue('demo.changed3');
  await expect(user).not.toHaveClass(/is-dirty/);
  await expect(config.getByText(/Configuration saved and read back/)).toBeVisible();
  const restart = config.getByRole('button', { name: 'Restart miner' });
  await expect(restart).toBeEnabled();
  const restartRequest = page.waitForRequest(request => request.url().endsWith('/restart') && request.method() === 'POST');
  await restart.click();
  expect((await restartRequest).postDataJSON()).toEqual({});
  await expect(config.getByText('A restart was observed through a lower uptime reading.', { exact: true })).toBeVisible();
  await expect(restart).toBeDisabled();
  await config.locator('.configuration-restart').screenshot({ path: 'test-results/configuration-restart.png' });
  await page.reload();
  await page.getByRole('link', { name: 'Fleet', exact: true }).click();
  await page.getByRole('button', { name: 'Bitaxe 3', exact: true }).click();
  await page.locator('.miner-disclosure > summary').first().click();
  await page.locator('.miner-disclosure > summary').nth(1).click();
  await expect(user).toHaveValue('demo.changed3');
  await expect(user).not.toHaveClass(/is-dirty/);
});


test('one account-only profile generates independent workers for selected miners and both pool destinations', async ({ page }) => {
  await page.goto(url);
  await page.getByRole('button', { name: 'Try demo' }).first().click();
  await page.getByRole('checkbox', { name: 'Select Bitaxe 2', exact: true }).check();
  await page.getByRole('checkbox', { name: 'Select Bitaxe 3', exact: true }).check();
  await page.getByRole('button', { name: 'Configure selected', exact: true }).click();
  await page.getByRole('combobox', { name: 'Load pool profile', exact: true }).selectOption({ label: 'Fallback profile' });
  await page.getByRole('combobox', { name: 'Load fallback pool profile', exact: true }).selectOption({ label: 'Fallback profile' });
  await expect(page.getByLabel('Payout address / account.worker', { exact: true })).toHaveValue('demo.demo-2');
  await expect(page.getByLabel('Fallback payout address / account.worker', { exact: true })).toHaveValue('demo.demo-2');
  const command = page.waitForRequest(request => request.url().endsWith('/api/batch') && request.method() === 'POST');
  await page.getByRole('button', { name: 'Apply & verify' }).click();
  const payload = (await command).postDataJSON();
  expect(payload.poolAccounts).toEqual({ primary: 'demo', fallback: 'demo' });
  expect(payload.settings).not.toHaveProperty('stratumUser');
  expect(payload.settings).not.toHaveProperty('fallbackStratumUser');
  await expect(page.locator('.results').getByText('Verified', { exact: true })).toHaveCount(2);
  const devices = await (await page.request.get(`${url}/api/devices`)).json();
  for (const index of [2, 3]) {
    const device = devices.find((d: { address: string }) => d.address === `demo-${index}`);
    expect(device.snapshot.settings.stratumUser).toBe(`demo.demo-${index}`);
    expect(device.snapshot.settings.fallbackStratumUser).toBe(`demo.demo-${index}`);
  }
  const profiles = await (await page.request.get(`${url}/api/pool-profiles`)).json();
  expect(profiles[0].settings.stratumAccount).toBe('demo');
  expect(profiles[0].settings).not.toHaveProperty('stratumUser');
  await page.locator('.configuration').screenshot({ path: 'test-results/profile-worker-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.configuration').screenshot({ path: 'test-results/profile-worker-mobile.png' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
