import { expect, test } from '@playwright/test';
test('miner routes start closed and activity loads one category on demand on desktop and mobile', async ({ page }) => {
  const requests: string[] = [];
  page.on('request', request => { if (request.url().includes('/api/')) requests.push(request.url()); });
  await page.route('**/api/devices', route => route.fulfill({ json: [{ id: 'fixture', name: 'Bitaxe 1', address: 'demo-1', demo: true, status: 'online', snapshot: { model: 'Gamma', settings: {}, capabilities: { writable: [], frequencies: [], voltages: [], poolMode: 'none' } } }] }));
  await page.route('**/api/devices/fixture/history?*', route => route.fulfill({ json: { metrics: [], events: [], changes: [], limit: 1000, hasMore: false } }));
  await page.goto('/');
  await page.getByRole('button', { name: 'Bitaxe 1', exact: true }).click();
  await expect(page).toHaveURL(/#miner\//);
  await expect(page.getByRole('table')).toHaveCount(0);
  await expect(page.locator('.miner-disclosure[open]')).toHaveCount(0);
  await expect(page.getByLabel('Chart metric')).toHaveValue('hashRate');
  await expect(page.getByLabel('Time range')).toHaveValue('1');
  expect(requests.some(url => /\/tuning|\/profiles/.test(url))).toBe(false);
  await page.screenshot({ path: 'test-results/miner-page-desktop.png', fullPage: true });
  await page.reload();
  await expect(page.locator('.miner-disclosure[open]')).toHaveCount(0);
  await page.getByRole('link', { name: 'Activity', exact: true }).click();
  await expect(page.getByRole('combobox', { name: 'Miner', exact: true })).toHaveValue('');
  requests.length = 0;
  await page.getByRole('combobox', { name: 'Miner', exact: true }).selectOption({ label: 'Bitaxe 1' });
  await expect(page.getByRole('button', { name: 'Previous', exact: true })).toBeDisabled();
  expect(requests.some(url => url.includes('section=events') && url.includes('pageSize=20'))).toBe(true);
  expect(requests.some(url => url.includes('section=metrics'))).toBe(false);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/activity-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('link', { name: 'Fleet', exact: true }).click();
  await page.getByRole('button', { name: 'Bitaxe 1', exact: true }).click();
  await expect(page.locator('.miner-disclosure > summary')).toHaveCount(2);
  await page.screenshot({ path: 'test-results/miner-page-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.goBack();
  await expect(page.getByRole('table')).toBeVisible();
});
