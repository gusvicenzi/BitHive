import { expect, test } from '@playwright/test';
test('collapsible active-pool groups, fleet graphs and individual VRM history work on desktop and mobile', async ({ page }) => {
  const settings = { stratumURL: 'pool.test', stratumPort: 3333, stratumUser: 'account.worker', fallbackStratumURL: 'solo.local', fallbackStratumPort: 3334, fallbackStratumUser: 'wallet.worker' };
  const devices = ['a', 'b', 'c'].map((id, index) => ({ id, name: `Miner ${id}`, address: `fixture-${id}`, demo: false, status: 'online', lastSeen: new Date().toISOString(), snapshot: { hashRate: 1200, power: 20, temp: 50 + index, vrTemp: 60 + index, isUsingFallbackStratum: index === 2, model: 'Gamma', settings, capabilities: { writable: [], frequencies: [], voltages: [], poolMode: 'none' } } }));
  const metrics = (index: number) => Array.from({ length: 50 }, (_, i) => ({ timestamp: new Date(Date.UTC(2026, 9, 28, 14, i)).toISOString(), hashRate: 1200 + Math.sin(i / 3 + index) * 50, power: 20 + Math.cos(i / 4 + index), temp: 50 + index * 2 + Math.sin(i / 4), vrTemp: 60 + index * 3 + Math.cos(i / 3), errorRate: 0 }));
  await page.route('**/api/devices', route => route.fulfill({ json: devices }));
  await page.route('**/api/pool-profiles', route => route.fulfill({ json: [{ id: 'p', name: 'Solo profile', settings: { stratumURL: 'solo.local', stratumPort: 3334, stratumAccount: 'wallet' } }] }));
  await page.route('**/api/fleet/history?*', route => route.fulfill({ json: { bucketMinutes: 1, series: devices.map((d, i) => ({ id: d.id, metrics: metrics(i) })) } }));
  await page.route('**/api/devices/a/history?*', route => route.fulfill({ json: { bucketMinutes: 1, metrics: metrics(0), events: [], changes: [], limit: 1000 } }));
  await page.goto('/');
  const groups = page.locator('.pool-group');
  await expect(groups).toHaveCount(2);
  await expect(groups.nth(0).locator('summary').first()).toContainText('2 / 2 online');
  await expect(groups.nth(1).locator('summary').first()).toContainText('Solo profile');
  await expect(groups.nth(1).locator('summary').first()).toContainText('1.2 TH/s');
  await groups.nth(1).locator('summary').first().click();
  await expect(groups.nth(1)).not.toHaveAttribute('open');
  await expect(page.getByRole('button', { name: 'Miner c', exact: true })).toBeHidden();
  await page.getByLabel('Filter by status').selectOption('online');
  await expect(groups.nth(1)).not.toHaveAttribute('open');
  await groups.nth(1).locator('summary').first().click();
  await page.getByLabel('Select Miner a', { exact: true }).check();
  await groups.nth(1).getByLabel('Select up to 50 visible miners', { exact: true }).check();
  await expect(page.getByLabel('Select Miner a', { exact: true })).toBeChecked();
  await expect(page.getByLabel('Select Miner c', { exact: true })).toBeChecked();
  const history = page.getByRole('region', { name: 'Fleet history' });
  await expect(history.locator('figure')).toHaveCount(4);
  const chip = page.getByRole('slider', { name: 'Inspect Chip temperature history' });
  const vrm = page.getByRole('slider', { name: 'Inspect VRM temperature history' });
  await expect(chip.locator('polyline')).toHaveCount(3);
  expect(new Set(await chip.locator('polyline').evaluateAll(lines => lines.map(line => line.getAttribute('stroke')))).size).toBe(3);
  await chip.focus(); await chip.press('Home');
  await expect(history.getByRole('tooltip')).toContainText('Miner a');
  await chip.press('Escape'); await chip.blur();
  await page.getByRole('button', { name: 'Toggle temperatures for Miner b' }).click();
  await expect(chip.locator('polyline')).toHaveCount(2);
  await expect(vrm.locator('polyline')).toHaveCount(2);
  await page.getByRole('button', { name: 'Toggle temperatures for Miner b' }).click();
  await page.screenshot({ path: 'test-results/fleet-history-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/fleet-history-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Miner a', exact: true }).click();
  await page.getByLabel('Chart metric').selectOption('vrTemp');
  await expect(page.getByRole('slider', { name: 'Inspect VRM temperature history' })).toBeVisible();
  await page.screenshot({ path: 'test-results/miner-vrm-mobile.png', fullPage: true });
  await page.getByLabel('Language').selectOption('pt-BR');
  await expect(page.getByRole('option', { name: 'Temperatura do VRM' })).toBeAttached();
});
