// @vitest-environment jsdom
import { afterEach, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import '@testing-library/jest-dom/vitest';
import '../src/web/i18n';
import { FleetHistory } from '../src/web/FleetHistory';
import { MinerHistory } from '../src/web/MinerHistory';
import type { DeviceView, MetricView } from '../src/shared/domain';
const miners = ['a', 'b'].map(id => ({ id, name: `Miner ${id}`, demo: false } as DeviceView));
const metrics = (temp: number): MetricView[] => [0, 60000].map(time => ({ timestamp: new Date(time).toISOString(), hashRate: 1000, power: 20, temp, vrTemp: temp + 10, errorRate: null }));
afterEach(() => { cleanup(); vi.unstubAllGlobals(); });
it('shows additive totals and distinctly colored per-miner temperatures with keyboard values and toggles', async () => {
  const fetch = vi.fn(async () => ({ ok: true, json: async () => ({ bucketMinutes: 1, series: miners.map((d, index) => ({ id: d.id, metrics: metrics(50 + index) })) }) }));
  vi.stubGlobal('fetch', fetch);
  const { container } = render(<FleetHistory devices={miners} revision={1} />);
  await screen.findByRole('slider', { name: 'Inspect Total hashrate history' });
  expect(container.querySelectorAll('figure')).toHaveLength(4);
  const power = screen.getByRole('slider', { name: 'Inspect Total power history' });
  fireEvent.focus(power); expect(screen.getByRole('tooltip')).toHaveTextContent('40.0 W');
  expect(screen.getByRole('tooltip')).toHaveTextContent('2 of 2 miners reporting');
  fireEvent.blur(power);
  const chip = screen.getByRole('slider', { name: 'Inspect Chip temperature history' });
  fireEvent.focus(chip);
  expect(screen.getByRole('tooltip')).toHaveTextContent('Miner a50.0');
  expect(screen.getByRole('tooltip')).toHaveTextContent('Miner b51.0');
  const chipLines = [...chip.querySelectorAll('polyline')];
  expect(chipLines[0].getAttribute('stroke')).not.toBe(chipLines[1].getAttribute('stroke'));
  const vrm = screen.getByRole('slider', { name: 'Inspect VRM temperature history' });
  expect(vrm.querySelector('polyline')?.getAttribute('stroke')).toBe(chipLines[0].getAttribute('stroke'));
  await userEvent.click(screen.getByRole('button', { name: 'Toggle temperatures for Miner a', exact: true }));
  expect(chip.querySelectorAll('polyline')).toHaveLength(1);
  expect(power.closest('figure')?.querySelector('figcaption')).toHaveTextContent('40 W');
  expect(fetch).toHaveBeenCalledTimes(1);
  await userEvent.selectOptions(screen.getByLabelText('Time range'), '24');
  expect(fetch.mock.calls).toHaveLength(2);
});
it('handles failed history and offers the individual VRM chart without a second request', async () => {
  vi.stubGlobal('fetch', vi.fn(async () => ({ ok: false, json: async () => ({ error: 'operationFailed' }) })));
  const { unmount } = render(<FleetHistory devices={miners} revision={1} />);
  expect(await screen.findByRole('alert')).toBeVisible(); unmount();
  const fetch = vi.fn(async () => ({ ok: true, json: async () => ({ metrics: metrics(50), bucketMinutes: 1, limit: 1000 }) }));
  vi.stubGlobal('fetch', fetch);
  render(<MinerHistory id="a" revision={1} />);
  await screen.findByRole('slider');
  await userEvent.selectOptions(screen.getByLabelText('Chart metric'), 'vrTemp');
  expect(within(screen.getByRole('figure')).getByText('VRM temperature')).toBeVisible();
  expect(fetch).toHaveBeenCalledTimes(1);
});
