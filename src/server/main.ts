import { Scheduler } from './scheduler.js';
import { PrismaClient } from '@prisma/client';
import { resolve } from 'node:path';
import { createApp } from './app.js';
import { FleetService } from './service.js';
import { Tuner } from './tuning.js';
import { Collector } from './collector.js';

const db = new PrismaClient();
const service = new FleetService(db);
const tuner = new Tuner(service, Date.now, () => console.error('Tuning cycle failed; recovery state is persisted.'));
const scheduler = new Scheduler(service, Date.now, () => console.error('Schedule cycle failed; command claims are persisted.'));
const app = await createApp(db, { service, tuner, scheduler, webRoot: process.env.BITHIVE_DEV ? undefined : resolve('dist/web'), dev: process.env.BITHIVE_DEV === '1' });
const collector = new Collector(service, () => console.error('Collection failed; retrying on the next cycle.'));
const port = Number(process.env.PORT ?? 3080);
if (!Number.isInteger(port) || port < 1 || port > 65535) throw new Error('Invalid PORT');
app.addHook('onClose', async () => { await scheduler.stop(); await tuner.stop(); await collector.stop(); await db.$disconnect(); });
for (const signal of ['SIGINT', 'SIGTERM'] as const) process.once(signal, () => { void app.close(); });
await app.listen({ host: '127.0.0.1', port });
await tuner.start();
collector.start();
scheduler.start();
console.log(`BitHive is ready at http://localhost:${port}`);
